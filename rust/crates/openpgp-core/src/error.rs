use openpgp_policy::ProfileError;
use thiserror::Error;

use crate::{FullFingerprint, SecretComponent};

#[derive(Debug, Error)]
pub enum KeyError {
    #[error("software protection password must not be empty")]
    EmptyPassword,
    #[error("user ID must not be empty")]
    EmptyUserId,
    #[error("the current password is required for protected private-key input")]
    PasswordRequired,
    #[error("could not unlock {component} with the supplied current password")]
    InvalidPassword {
        component: SecretComponent,
        #[source]
        source: pgp::errors::Error,
    },
    #[error("secret material does not match the public parameters in {component}")]
    SecretMaterialMismatch { component: SecretComponent },
    #[error("secret material in {component} is not password-protected")]
    UnprotectedSecret { component: SecretComponent },
    #[error("no key with full fingerprint {fingerprint}")]
    KeyNotFound { fingerprint: FullFingerprint },
    #[error("private-key export is disabled for {fingerprint}")]
    PrivateExportDisabled { fingerprint: FullFingerprint },
    #[error("key {fingerprint} is public-only")]
    SecretKeyRequired { fingerprint: FullFingerprint },
    #[error("a different certificate with fingerprint {fingerprint} is already stored")]
    ConflictingCertificate { fingerprint: FullFingerprint },
    #[error("input contains more than one certificate")]
    MultipleCertificates,
    #[error("input mixes public and private certificates")]
    MixedKeyring,
    #[error("input contains trailing data")]
    TrailingData,
    #[error("input contains data before the ASCII armor")]
    LeadingData,
    #[error("unexpected OpenPGP packet at index {index}")]
    UnexpectedPacket { index: usize },
    #[error("key component at packet index {index} has no binding signature")]
    MissingBinding { index: usize },
    #[error("input is empty")]
    EmptyInput,
    #[error("invalid key generation parameters: {0}")]
    InvalidParameters(String),
    #[error("algorithm {algorithm:?} cannot be generated by this software backend")]
    UnsupportedGenerationAlgorithm {
        algorithm: openpgp_policy::Algorithm,
    },
    #[error(transparent)]
    Profile(#[from] ProfileError),
    #[error(transparent)]
    OpenPgp(#[from] pgp::errors::Error),
    #[error(transparent)]
    Io(#[from] std::io::Error),
}
